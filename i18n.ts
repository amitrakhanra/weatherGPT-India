export function localizeNumerals(str: string | number | null | undefined, lang: string): string {
  if (str == null) return '';
  const map = DIGIT_MAPS[lang];
  if (!map) return String(str);
  return String(str).replace(/[0-9]/g, d => map[+d]);
}

